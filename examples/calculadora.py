"""Funções aritméticas simples usadas como exemplo para o gerador de testes."""


def add(a: float, b: float) -> float:
    """Retorna a soma de ``a`` e ``b``.

    Args:
        a: Primeira parcela.
        b: Segunda parcela.

    Returns:
        O resultado de ``a + b``.
    """
    return a + b


def subtract(a: float, b: float) -> float:
    """Retorna a diferença entre ``a`` e ``b``.

    Args:
        a: Minuendo.
        b: Subtraendo.

    Returns:
        O resultado de ``a - b``.
    """
    return a - b
